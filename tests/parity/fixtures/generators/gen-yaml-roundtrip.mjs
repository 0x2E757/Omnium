// Differential fixture generator: yaml-roundtrip-real.json (design-code-reviewer §Q3 tests item 1).
//
// MUST be run from inside the reference checkout (cwd = <ref-checkout>),
// which has the real `yaml` package installed — the library is resolved from the
// CURRENT WORKING DIRECTORY. It reads real committed meta files from BOTH prior
// stores via absolute paths:
//
//   cd <ref-checkout> && node /path/to/Omnium/tests/parity/fixtures/generators/gen-yaml-roundtrip.mjs
//
// Records ~10 diverse real meta files verbatim: { relativeName, rawBytes,
// parsedValue }. Parity tests assert (a) vendored parse(rawBytes) deep-equals
// parsedValue and (b) vendored serializeMeta(parseMeta(rawBytes)) === rawBytes.

import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const require = createRequire(join(process.cwd(), "package.json"));
const yaml = require("yaml");
const yamlVersion = require("yaml/package.json").version;

// Diverse picks: many-edge, multi-tag-edge, single-edge, deep paths, .md nodes.
const picks = [
  // Graphyne store
  ["Graphyne", "DESIGN.md.yaml"], // 9 doc edges
  ["Graphyne", "src/common/engine.mts.yaml"], // largest file in the store
  ["Graphyne", "src/common/storage.mts.yaml"], // many edges, mixed tags
  ["Graphyne", "src/service.mts.yaml"], // single edge, single tag
  ["Graphyne", "scripts/build-plugin.mjs.yaml"], // 2 edges, consumer tag
  ["Graphyne", "src/claude/hook.mts.yaml"], // hook node
  // Memosyne store
  ["Memosyne", "src/mcp/handlers.mts.yaml"], // 8 edges
  ["Memosyne", "src/claude/hook.mjs.yaml"], // edge carrying 2 tags
  ["Memosyne", "src/web/assets/js/components/index.js.yaml"], // deep path segments
  ["Memosyne", "src/claude/plugin/commands/setup.md.yaml"], // .md node, multi-tag edge
];

const repoRoots = {
  Graphyne: process.env.REF_GRAPHYNE_DIR ?? "/path/to/graphyne-checkout",
  Memosyne: process.env.REF_MEMOSYNE_DIR ?? "/path/to/memosyne-checkout",
};

const files = picks.map(([repo, rel]) => {
  const abs = join(repoRoots[repo], ".graphyne/meta", rel);
  const rawBytes = readFileSync(abs, "utf8");
  return {
    relativeName: `${repo}/.graphyne/meta/${rel}`,
    rawBytes,
    parsedValue: yaml.parse(rawBytes),
  };
});

const fixture = {
  _notes:
    "Real committed meta files copied verbatim from the reference meta stores; parsedValue is yaml@" +
    yamlVersion + " parse(rawBytes). Tier-1 proof on real data: the vendored parser must produce " +
    "parsedValue and the vendored emitter must reproduce rawBytes byte-for-byte from it. " +
    "Generated by gen-yaml-roundtrip.mjs run inside the reference checkout.",
  library: "yaml",
  version: yamlVersion,
  files,
};

const out = new URL("../yaml-roundtrip-real.json", import.meta.url);
writeFileSync(out, JSON.stringify(fixture, null, 2) + "\n");
console.log(`wrote ${out.pathname}: ${files.length} files (yaml@${yamlVersion})`);
